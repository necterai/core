/**
 * Generates src/catalog.lite.ts: the signal catalog without human-readable
 * descriptions / false-positive notes. The browser SDK only needs weights,
 * layers, families and class profiles at runtime, and the prose roughly
 * doubles the size of core in the client bundle. Run by `pnpm build`.
 */
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { SIGNAL_CATALOG } from '../src/catalog.js';

const lite = SIGNAL_CATALOG.map((d) => {
  const o: Record<string, unknown> = { id: d.id, layer: d.layer, strength: d.strength, automation: d.automation, source: d.source, description: '' };
  if (d.classes) o['classes'] = d.classes;
  if (d.family) o['family'] = d.family;
  return o;
});
const out = `// GENERATED by scripts/gen-lite.ts from catalog.ts. Do not edit.
import type { SignalDefinition } from './signals.js';

export const SIGNAL_CATALOG_LITE: SignalDefinition[] = ${JSON.stringify(lite)};
`;
writeFileSync(fileURLToPath(new URL('../src/catalog.lite.ts', import.meta.url)), out);
console.log(`catalog.lite.ts: ${lite.length} definitions`);
