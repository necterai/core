/** Shared helpers for the IP-range normaliser and sync scripts (Node only; never used at runtime). */
import { existsSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, join, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import type { IpRangeSet, IpSource } from '../src/types.js';

export const PKG_ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
export const IP_DIR = join(PKG_ROOT, 'data', 'ip-ranges');
export const RAW_DIR = join(IP_DIR, 'raw');
export const SYNC_CACHE_DIR = join(IP_DIR, 'sync-cache');
export const GENERATED_FILE = join(PKG_ROOT, 'src', 'generated', 'ip-ranges.ts');

export function loadSources(): IpSource[] {
  return JSON.parse(readFileSync(join(IP_DIR, 'sources.json'), 'utf8')) as IpSource[];
}

export function writeRangeSet(dir: string, set: IpRangeSet): string {
  mkdirSync(dir, { recursive: true });
  const file = join(dir, `${set.id}.json`);
  // Compact prefixes (one per line) keep diffs readable without bloating the file.
  const { prefixes, ...meta } = set;
  const head = JSON.stringify(meta, null, 2).replace(/\n}$/, '');
  const body = prefixes.length ? `[\n    ${prefixes.map((p) => JSON.stringify(p)).join(',\n    ')}\n  ]` : '[]';
  writeFileSync(file, `${head},\n  "prefixes": ${body}\n}\n`);
  return file;
}

/** Regenerate src/generated/ip-ranges.ts with a static import per bundled range file present on disk. */
export function writeGeneratedIndex(sources: IpSource[]): string[] {
  const present = sources.filter((s) => s.bundled && existsSync(join(IP_DIR, `${s.id}.json`)));
  const rel = relative(dirname(GENERATED_FILE), IP_DIR).split('\\').join('/');
  const lines = [
    '// AUTO-GENERATED by scripts/normalise-ip-ranges.ts / scripts/sync-ip-ranges.ts. Do not edit.',
    '// One static JSON import per bundled range file so bundlers inline the data.',
    "import type { IpRangeSet } from '../types.js';",
    ...present.map((s, i) => `import r${i} from '${rel}/${s.id}.json';`),
    '',
    `export const bundledIpRanges: IpRangeSet[] = [${present.map((_, i) => `r${i}`).join(', ')}] as IpRangeSet[];`,
    '',
  ];
  mkdirSync(dirname(GENERATED_FILE), { recursive: true });
  writeFileSync(GENERATED_FILE, lines.join('\n'));
  return present.map((s) => s.id);
}

export function rawFiles(): string[] {
  return existsSync(RAW_DIR) ? readdirSync(RAW_DIR).filter((f) => !f.startsWith('.')) : [];
}
